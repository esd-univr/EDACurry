int NgspiceBackend::visitParameter(const std::shared_ptr<structure::Parameter> &e, std::string passive_component_type)
{
    bool left_ignored = false;
    if ((e->getType() == param_assign) || (e->getType() == param_arithmetic)) {
        if (e->getLeft() && !e->getHideName()) {
            auto ident = std::dynamic_pointer_cast<const structure::Identifier>(e->getLeft());
            std::string identifier;
            if (ident) {
                identifier = ident->getName();
                std::transform(std::begin(identifier), std::end(identifier), std::begin(identifier), ::tolower);

                if (is_eldo_only(identifier)) {
                    std::string warning_message;
                    warning_message.append("[NgspiceBackend::visitParameter] Parameter ").append(identifier)
                            .append(" is not supported by ngspice. Ignored by visitor\n");
                    warnings.push_back(warning_message);
                    std::cerr << warning_message << std::endl;
                    return 1;
                }
            }

            if (passive_component_type.empty()){
                e->getLeft()->accept(this);
            } else {
                if (passive_component_type == "R") {
                    if (identifier != "r") {
                        e->getLeft()->accept(this);
                    } else {
                        left_ignored = true;
                    }
                } else if (passive_component_type == "C") {
                    if (identifier != "c") {
                        e->getLeft()->accept(this);
                    } else {
                        left_ignored = true;
                    }
                } else if (passive_component_type == "L") {
                    if (identifier != "l") {
                        e->getLeft()->accept(this);
                    } else {
                        left_ignored = true;
                    }
                }
            }
        }
        if (e->getRight()) {
            auto ident = std::dynamic_pointer_cast<const structure::Identifier>(e->getRight());
            if (ident) {
                std::string identifier = ident->getName();
                std::transform(std::begin(identifier), std::end(identifier), std::begin(identifier), ::tolower);
                if (is_eldo_only(identifier)) {
                    std::string warning_message;
                    warning_message.append("[NgspiceBackend::visitParameter] Parameter ").append(identifier).append(" is not supported by ngspice. Ignored by visitor\n");
                    warnings.push_back(warning_message);
                    std::cerr << warning_message << std::endl;
                    return 1;
                }
            }
            if (!left_ignored && e->getLeft() && !e->getHideName())
                ss << '=';
            if (e->getType() == param_arithmetic)
                ss << '{';
            e->getRight()->accept(this);
            if (e->getType() == param_arithmetic)
                ss << '}';
        }
    } else if (e->getType() == param_tabular) {
        const std::string &warning_message {"[NgspiceBackend::visitParameter] Tabular parameter is not supported by ngspice. "
                                            "Ignored by visitor\n"};
        warnings.push_back(warning_message);
        std::cerr << warning_message << std::endl;
        return 1;
    } else if (e->getType() == param_list) {
        if (e->getLeft()) {
            auto ident = std::dynamic_pointer_cast<const structure::Identifier>(e->getLeft());
            if (ident) {
                std::string identifier = ident->getName();
                std::transform(std::begin(identifier), std::end(identifier), std::begin(identifier), ::tolower);
                if (is_eldo_only(identifier)) {
                    std::string warning_message;
                    warning_message.append("[NgspiceBackend::visitParameter] Parameter ").append(identifier)
                            .append(" is not supported by ngspice. Ignored by visitor\n");
                    warnings.push_back(warning_message);
                    std::cerr << warning_message << std::endl;
                    return 1;
                }
            }
            e->getLeft()->accept(this);
        }
        ss << "(";
        auto table = std::dynamic_pointer_cast<const structure::ValueList>(e->getRight());
        for (size_t i = 0; table && (i < table->values.size()); ++i) {
            table->values[i]->accept(this);
            if (i < (table->values.size() - 1))
                ss << ' ';
        }
        ss << ')';
    } else if (e->getType() == param_no_equal) {
        if (e->getLeft()) {
            auto ident = std::dynamic_pointer_cast<const structure::Identifier>(e->getLeft());
            if (ident) {
                std::string identifier = ident->getName();
                std::transform(std::begin(identifier), std::end(identifier), std::begin(identifier), ::tolower);
                if (is_eldo_only(identifier)) {
                    std::string warning_message;
                    warning_message.append("[NgspiceBackend::visitParameter] Parameter ").append(identifier)
                            .append(" is not supported by ngspice. Ignored by visitor\n");
                    warnings.push_back(warning_message);
                    std::cerr << warning_message << std::endl;
                    return 1;
                }
            }
            e->getLeft()->accept(this);
        }
        if (e->getRight()) {
            auto ident = std::dynamic_pointer_cast<const structure::Identifier>(e->getRight());
            if (ident) {
                std::string identifier = ident->getName();
                std::transform(std::begin(identifier), std::end(identifier), std::begin(identifier), ::tolower);
                if (is_eldo_only(identifier)) {
                    std::string warning_message;
                    warning_message.append("[NgspiceBackend::visitParameter] Parameter ").append(identifier)
                            .append(" is not supported by ngspice. Ignored by visitor\n");
                    warnings.push_back(warning_message);
                    std::cerr << warning_message << std::endl;
                    return 1;
                }
            }
            if (e->getLeft())
                ss << " ";
            e->getRight()->accept(this);
        }
    }
    return 0;
}

int NgspiceBackend::visitSubckt(const std::shared_ptr<structure::Subckt> &e)
{
    ss << ".subckt " << e->getName();
    for (const auto &node : e->nodes) {
        ss << ' ';
        node->accept(this);
    }
    // parameters must be declared on the same line of the subckt declaration
    if (e->parameters) {
        for (const auto &parameter : e->parameters) {
            ss << ' ';
            parameter->accept(this);
        }
    }
    ss << '\n';
    ss << ind_increase;
    for (const auto &entry : e->content) {
        entry->accept(this);
    }
    ss << ind_decrease;
    ss << ".ends " << e->getName() << '\n';
    return 0;
}

int NgspiceBackend::visitString(const std::shared_ptr<structure::String> &e)
{
    ss << e->getString();
    return 0;
}

int NgspiceBackend::visitValuePair(const std::shared_ptr<structure::ValuePair> &e)
{
    if (e->getFirst()) {
        e->getFirst()->accept(this);
    }
    ss << ',';
    if (e->getSecond()) {
        e->getSecond()->accept(this);
    }
    return 0;
}

int NgspiceBackend::visitValueList(const std::shared_ptr<structure::ValueList> &e)
{
    ss << delimiter_type_open_char(e->getDelimiterType());
    if (e->values) {
        size_t size = e->values.size(), i = 0;
        for (const auto &value : e->values) {
            value->accept(this);
            if (i++ < (size - 1))
                ss << ", ";
        }
    }
    ss << delimiter_type_close_char(e->getDelimiterType());
    return 0;
}

std::pair<std::string, std::vector<std::string>> write_ngspice(const std::shared_ptr<structure::Object> &object) {
    edacurry::backend::NgspiceBackend backend;
    object->accept(&backend);
    return {backend.str(), backend.getWarnings()};
}

